## Le deck

Chaque joueur a un **deck de 60 cartes** exactement, avec au maximum 4 exemplaires d’une même carte (sauf les cartes Énergie de base). Il existe trois types de cartes :

- **Les cartes Pokémon** : de base, ou évolutions (Niveau 1, Niveau 2), et les Pokémon-ex.
- **Les cartes Énergie** : nécessaires pour attaquer.
- **Les cartes Dresseur** : Objets, Supporters et Stades, qui vous aident pendant la partie.

Pour débuter, le plus simple est un deck prêt à jouer comme le [Starter Set ex Évoli-ex](product:deck-starter-set-ex-evoli-ex).

## La mise en place

1. Mélangez votre deck et piochez 7 cartes.
2. Posez un Pokémon de base face cachée comme **Pokémon Actif**, et jusqu’à 5 Pokémon de base sur votre **Banc**.
3. Mettez de côté les 6 premières cartes de votre deck, face cachée : ce sont vos **cartes Récompense**.
4. Lancez une pièce pour savoir qui commence, puis retournez vos Pokémon.

## Le tour de jeu

À chaque tour, piochez une carte, puis dans l’ordre de votre choix :

- posez des Pokémon de base sur votre Banc ;
- faites évoluer vos Pokémon ;
- attachez **une seule carte Énergie** par tour à l’un de vos Pokémon ;
- jouez des cartes Dresseur (un seul Supporter par tour) ;
- faites battre en retraite votre Pokémon Actif en défaussant des Énergies.

Terminez votre tour en **attaquant** avec votre Pokémon Actif, s’il a les Énergies nécessaires.

## Mettre K.O. et gagner

Quand les dégâts d’un Pokémon atteignent ses points de vie, il est **K.O.** : vous prenez une carte Récompense (deux pour un Pokémon-ex, trois pour un Méga-Pokémon-ex). Vous gagnez si :

- vous prenez vos 6 cartes Récompense ;
- votre adversaire n’a plus de Pokémon en jeu ;
- votre adversaire ne peut plus piocher au début de son tour.

## Construire son deck

Un bon premier deck compte environ 15 à 20 Pokémon, 10 à 15 Énergies et 25 à 30 cartes Dresseur. Achetez des boosters, un [Coffret Dresseur d’Élite](category:etb) ou des [decks](category:premium) pour compléter votre collection. Les cartes japonaises se jouent entre amis ; en tournoi officiel, seules les versions internationales sont autorisées.

