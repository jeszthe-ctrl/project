## Where the wirehaired dachshund came from

Wirehaired dachshunds were developed in Germany in the late 1800s by crossing smooth dachshunds with rough-coated terriers and pinschers. Hunters wanted a dachshund whose coat could protect it from thorns, brambles and cold, wet ground. The terrier influence also shows in the wire's lively personality.

