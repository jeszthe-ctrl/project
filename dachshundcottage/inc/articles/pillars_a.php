## Health: what every mini dachshund owner should know

### Back problems (IVDD)

Intervertebral disc disease is the biggest health risk in dachshunds of both sizes; roughly one in four dachshunds has back problems in their lifetime. You can lower the risk:

- Keep your mini lean: you should feel the ribs and see a waist
- Use ramps or steps for sofas, beds and cars
- Don't let them jump off furniture
- Lift with one hand under the chest and one under the rear
- Walk them on a harness, not a collar

