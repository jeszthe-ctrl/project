## How to hand-strip a wirehaired dachshund (basics)

1. Brush the coat first to remove tangles.
2. Hold the skin taut with one hand.
3. Grip a few long, dead hairs between thumb and a stripping knife or finger.
4. Pull gently in the direction of growth; dead hairs come out easily.
5. Work in small sections, body first, then legs; tidy the beard and eyebrows with scissors.

If hairs don't come out easily, the coat isn't ready. Many owners have a groomer strip twice a year and "roll" the coat at home between visits.

