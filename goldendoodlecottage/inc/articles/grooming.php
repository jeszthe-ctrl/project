## How to line brush

1. Mist the coat with detangling spray.
2. Part a line in the coat so you can see the skin.
3. Brush the hair below the line out and down, from the skin.
4. Move the part up an inch and repeat over the whole body.
5. Comb to check: the comb should slide to the skin.

