## Where cavapoos come from

Breeders in Australia began crossing Cavalier King Charles spaniels with poodles on purpose in the 1990s, aiming for a gentle companion with a low-shedding coat. There the dogs are called cavoodles; in America, cavapoos. The cavapoo is a crossbreed, not a breed recognized by the American Kennel Club, which is why the parents' health matters so much.

## Cavalier King Charles spaniel or King Charles spaniel?

The Cavalier King Charles spaniel and the King Charles spaniel (English toy spaniel) are two different breeds. Cavapoos are bred from Cavaliers, which have a longer muzzle and are a little larger. "King Charles cavapoo" and "Cavalier cavapoo" usually mean the same dog.

