## Where bernedoodles come from

People have crossed poodles with other breeds for decades, but the bernedoodle as we know it was first bred on purpose in 2003 by Canadian breeder Sherry Rupke. The goal: the Bernese mountain dog's sweet, devoted temperament with a poodle's intelligence, lower-shedding coat and often longer life.

The bernedoodle is a crossbreed, not a breed recognized by the American Kennel Club. That's why the parents' health and the breeder's care matter so much.

