## Where the golden retriever comes from

The golden retriever was developed on the Guisachan estate in the Scottish Highlands by Dudley Marjoribanks, later Lord Tweedmouth. In 1868 he bred a yellow wavy-coated retriever named Nous to a Tweed water spaniel named Belle, and kept careful records of the puppies and the generations that followed. He wanted a gundog that was gentle-mouthed, tireless in cold water and easy to work with.

The Kennel Club in Britain recognized the breed in 1911, and the American Kennel Club in 1925. The Golden Retriever Club of America was founded in 1938 and still sets the health recommendations most responsible breeders follow.

