## Coat and grooming

Both breeds shed a lot. A golden's longer coat and feathering need more brushing and catch more burrs and mud. A Lab's short coat is quicker to brush and dries faster after swimming, but Lab hair still gets everywhere.

## Temperament

Both are friendly, social and great with families. Owners often describe goldens as a little softer and more sensitive to tone of voice, and Labs as a little more boisterous, confident and food-motivated. Individual dogs vary more than the breeds do.

## Training

Both are among the easiest breeds to train. Labs' love of food makes treats very effective; goldens are especially eager to please. Both need early work on jumping, leash walking and mouthing.

## Exercise

Both need at least an hour of exercise a day and love swimming and fetch. Young Labs and field-line goldens can be especially high-energy.

## Health

