The golden retriever and the Labrador retriever are America's two favorite retrievers, and for good reason. They have a lot in common, but there are real differences worth knowing before you choose.

## Golden retriever vs Labrador at a glance

| | Golden retriever | Labrador retriever |
|---|---|---|
| Origin | Scotland | Newfoundland, developed in Britain |
| Height | 21.5–24 in | 21.5–24.5 in |
| Weight | 55–75 lb | 55–80 lb |
| Coat | Medium-long, feathered double coat | Short, dense double coat |
| Colors | Light golden to dark golden (cream in British lines) | Black, yellow, chocolate |
