## The classic schnauzer cut, step by step

### Tools

- Clippers with a #10 blade (and a #7F or #4F for the body if you want it a little longer)
- Straight and curved scissors, plus thinning shears
- Slicker brush and a metal comb
- Nail clippers

### Steps

1. **Bathe and dry** your schnauzer and brush out every tangle.
2. **Body:** clip the back, neck and sides with the grain, from the base of the skull to the tail. Stop where the ribs curve down, leaving the "skirt" longer.
3. **Head:** clip the top of the head and cheeks short, from the outer corner of the eye back.
4. **Ears:** clip the outer ear lightly and trim the edges with scissors.
5. **Eyebrows:** comb forward and cut each eyebrow on a diagonal, from the outer corner to the inner corner, so they form two triangles.
6. **Beard:** comb forward and square it off; trim any stray hairs under the chin.
7. **Legs and underside:** comb the furnishings out and scissor them into neat columns and a straight skirt line.
8. **Feet:** trim around the paws for a round, tidy shape and clip the hair between the pads.
9. **Hygiene areas:** clip the belly and under the tail short.

Always clip with the direction of hair growth, keep blades cool, and take your time around the eyes, ears and belly.

