## Step 1: brush and comb out

Brush the whole dog with the slicker, then comb every area down to the skin, paying attention to the beard, armpits, legs and behind the ears. Never bathe a matted dog: water tightens mats. Cut out mats you can't comb, carefully, sliding the comb between the mat and the skin first.

## Step 2: bathe and dry

Bathe with dog shampoo, rinse thoroughly and dry completely, fluffing the legs and beard. Clippers glide better through clean, dry hair.

## Step 3: clip the body

With a **#7F or #10 blade**, clip *with* the direction of hair growth:

1. Start at the back of the skull and clip down the neck and back to the tail.
2. Clip the sides down to just above the elbow and to the bottom of the ribs, curving up toward the hips. That line is where the skirt begins.
3. Clip the chest from the throat down to just above the breastbone.
4. Clip the rear and the back of the thighs down to the hock area, blending into the legs.

## Step 4: head and ears

