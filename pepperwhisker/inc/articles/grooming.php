Learning to groom your own schnauzer saves money and keeps your dog comfortable between professional cuts. Here's how to do the classic [schnauzer haircut](/guides/schnauzer-haircut-styles) at home.

## Tools you need

- **Slicker brush** and a **metal greyhound comb** (wide and fine teeth)
- **Clippers** with blades: #10 (head and ears), #7F (body) and #40 or #30 for paw pads
- **Straight scissors** and **thinning shears**, plus small rounded-tip scissors for the face
