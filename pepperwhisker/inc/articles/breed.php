## Why the miniature schnauzer is called a terrier

Miniature schnauzers were bred to catch rats on German farms, the same job many terriers did. When the AKC recognized the breed in 1926, it placed it with the terriers because of its size and ratting background.

## How schnauzers differ from true terriers

Most terriers were bred in Britain to dig and fight vermin underground, which made them tenacious and sometimes scrappy with other dogs. Schnauzers were all-round farm dogs. Miniature schnauzers are usually friendlier with other dogs and more eager to please than many terriers.

