## What merle looks like

Merle creates a marbled coat: patches of full color on a diluted background. A blue merle schnauzer has black patches on a blue-grey coat. Merles often have blue or odd-colored eyes.

## Where merle comes from

Merle is a dominant gene found in breeds like collies, Australian shepherds and dachshunds. It never appeared in schnauzers historically, so a merle schnauzer has another breed somewhere in its ancestry.

## The health risk: double merle

A puppy that inherits merle from both parents (a double merle) is often mostly white and has a high risk of:

- deafness in one or both ears
- small or malformed eyes and blindness

Responsible breeders never breed two merles together.

