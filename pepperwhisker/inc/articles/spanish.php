## Schnauzer miniatura

El schnauzer miniatura (o schnauzer mini) es el más popular: alegre, cariñoso, inteligente y muy alerta. Se adapta bien a pisos y familias con niños, aunque ladra bastante. La FCI acepta cuatro colores: sal y pimienta, negro, negro y plata, y blanco. En inglés, lee nuestra [guía del miniature schnauzer](/guides/miniature-schnauzer).

## Schnauzer gigante

El schnauzer gigante es un perro de trabajo grande, potente y protector, criado en Baviera para conducir ganado y vigilar. Necesita mucho ejercicio, adiestramiento constante y un dueño con experiencia. Más información (en inglés): [giant schnauzer](/guides/giant-schnauzer).

## Cuidados del pelo

El pelo duro del schnauzer casi no se cae, por eso muchas personas con alergias leves lo toleran bien. Hay que cepillarlo dos o tres veces por semana, limpiar la barba después de comer y cortarlo o hacer *stripping* cada 5–8 semanas.

## Salud

El schnauzer miniatura tiene tendencia a la pancreatitis y a las grasas altas en sangre, por eso conviene una dieta moderada en grasa y evitar las sobras de comida. También puede sufrir cálculos urinarios, diabetes y problemas oculares. El gigante puede tener displasia de cadera e hipotiroidismo.

