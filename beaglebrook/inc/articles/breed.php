Use a **rubber curry brush or hound grooming mitt** once or twice a week, working in the direction of the coat. It lifts loose hair and spreads natural oils. In shedding season, brush daily; a de-shedding tool used gently once a week also helps.

### Bathing
Bathe every month or two with a dog shampoo — or sooner if your beagle has rolled in something, which beagles love to do. Too-frequent bathing dries the skin and can increase shedding.

### Ears
Beagle ears are long and floppy, so air doesn't circulate well inside. Check them weekly and clean with a vet-recommended ear cleaner. Redness, odor, head shaking or scratching mean a vet visit.

### Nails and teeth
Trim nails every 3 to 4 weeks, and brush teeth several times a week with dog toothpaste.

## What makes shedding worse?

- **Poor diet:** a complete, balanced food with healthy fats supports skin and coat. See [best dog food for beagles](/guides/best-dog-food-for-beagles).
- **Allergies, parasites and skin infections:** patchy hair loss, itching, redness or sores need a vet.
- **Stress and illness:** sudden heavy shedding outside of spring and fall is worth mentioning to your vet.
- **Over-bathing** with harsh shampoos.

## Tips for living with a shedding beagle

- Keep a lint roller by the door and a washable throw on their favorite sofa spot.
- Vacuum with a pet-hair attachment once or twice a week.
- Wash bedding weekly.
- Brush outdoors in shedding season.

## Questions

### Do beagle puppies shed?
Puppies shed less at first. Their adult coat comes in between about 6 and 12 months, and adult shedding follows.

### Do lemon or tricolor beagles shed more?
No. All beagles have the same coat type and shed the same amount. You'll just notice light hairs more on dark fabrics, and vice versa.

### Should I shave my beagle to reduce shedding?
No. A beagle's coat protects them from sun, heat and cold. Shaving doesn't stop shedding and can damage the coat.

